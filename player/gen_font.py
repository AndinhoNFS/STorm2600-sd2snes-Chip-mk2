# Generates font_txt.inc: 2bpp BG2 tiles + the 4 text rows (32 words each).
# tile 0 = transparent, tile 1 = space (transparent), tiles 2.. = glyphs (white on dark).
G={
'B':["####.","#...#","#...#","####.","#...#","#...#","####."],
'C':[".###.","#...#","#....","#....","#....","#...#",".###."],
'W':["#...#","#...#","#...#","#.#.#","#.#.#","##.##","#...#"],
'a':[".....",".....",".###.","....#",".####","#...#",".####"],
'c':[".....",".....",".####","#....","#....","#....",".####"],
'e':[".....",".....",".###.","#...#","#####","#....",".###."],
'h':["#....","#....","#.##.","##..#","#...#","#...#","#...#"],
'i':["..#..",".....",".##..","..#..","..#..","..#..",".###."],
'k':["#....","#....","#..#.","#.#..","##...","#.#..","#..#."],
'l':[".##..","..#..","..#..","..#..","..#..","..#..",".###."],
'o':[".....",".....",".###.","#...#","#...#","#...#",".###."],
'r':[".....",".....","#.##.","##..#","#....","#....","#...."],
't':[".#...",".#...","####.",".#...",".#...",".#..#","..##."],
'-':[".....",".....",".....","#####",".....",".....","....."],
'/':["....#","....#","...#.","..#..",".#...","#....","#...."],
'E':["#####","#....","#....","####.","#....","#....","#####"],
'H':["#...#","#...#","#...#","#####","#...#","#...#","#...#"],
'd':["....#","....#",".####","#...#","#...#","#...#",".####"],
's':[".....",".....",".####","#....",".###.","....#","####."],
'y':[".....",".....","#...#","#...#",".####","....#",".###."],
'N':["#...#","##..#","##..#","#.#.#","#..##","#..##","#...#"],
'm':[".....",".....","##.#.","#.#.#","#.#.#","#.#.#","#.#.#"],
'1':["..#..",".##..","..#..","..#..","..#..","..#..",".###."],
'2':[".###.","#...#","....#","...#.","..#..",".#...","#####"],
'3':["#####","...#.","..#..","...#.","....#","#...#",".###."],
}
order=[' ']+sorted(G)           # ' ' = tile 1
names=["Color-1","Color-2","Color-3","Black/White","Easy","Normal","Hard"]
tile=lambda ch:order.index(ch)+1
out=["; generated by gen_font.py -- do not edit","FontTiles:"]
out.append("    .byte "+",".join(["0"]*16)+"   ; tile 0: transparent")
for ch in order:
    rows=[] if ch==' ' else G[ch]
    b=[]
    for r in range(8):
        bits=0
        if ch!=' ' and 1<=r<=7:
            s=rows[r-1]
            for c,x in enumerate(s):
                if x=='#': bits|=0x40>>c      # columns 1..5
        b+=[bits,bits]                         # glyph pixels = colour 3, everything else transparent (no background)
    out.append("    .byte "+",".join("$%02X"%v for v in b)+"   ; '%s'"%ch)
out.append("FONTLEN = %d"%((len(order)+1)*16))
out.append("TxtRows:")
for n in names:
    s=n.center(12)
    assert len(s)==12
    words=[0]*32
    for i,ch in enumerate(s): words[10+i]=tile(ch)|0x2000    # columns 10..21, priority bit
    out.append("    .word "+",".join("$%04X"%w for w in words)+"   ; "+n)
open('font_txt.inc','w').write("\n".join(out)+"\n")
print("ok",len(order)+1,"tiles")
